    pattern = extract.template_pattern("Order #${id} failed: 50% [retry] (a|b)")
    assert pattern == r"Order #.* failed: 50% \[retry] \(a\|b\)"
    assert re.search(pattern, "Order #12 failed: 50% [retry] (a|b)")


