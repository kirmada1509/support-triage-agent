def line_of(source: str, text: str) -> int:
    return next(i for i, line in enumerate(source.splitlines(), 1) if text in line)


def test_languages_come_from_file_extensions():
    assert extract.language("src/payment/charge.js") == "javascript"
    assert extract.language("src/checkout/main.go") == "go"
    assert extract.language("src/quote/app/routes.php") == "php"
    assert extract.language("src/cart/src/services/CartService.cs") == "csharp"
    assert extract.language("src/payment/package.json") is None


def test_javascript_symbols():
    found = {(s.name, s.kind, s.line) for s in extract.symbols("x.js", CHARGE_JS, "javascript")}
    assert ("charge", "function", line_of(CHARGE_JS, "module.exports.charge")) in found
    assert ("luhn", "function", line_of(CHARGE_JS, "function luhn")) in found
    handler = extract.symbols("index.js", INDEX_JS, "javascript")[0]
    assert handler.name == "chargeServiceHandler"
    assert handler.signature == "async function chargeServiceHandler(call, callback)"


def test_go_symbols_carry_receivers_and_signatures():
    found = {s.name: s for s in extract.symbols("main.go", CHECKOUT_GO, "go")}
    assert found["checkout"].kind == "struct"
    place = found["PlaceOrder"]
    assert place.kind == "method" and place.line == line_of(CHECKOUT_GO, "PlaceOrder(")
    assert place.signature.startswith("func (cs *checkout) PlaceOrder(ctx context.Context")
    assert "{" not in place.signature
    assert found["mustMapEnv"].kind == "function"


def test_php_symbols():
    found = {(s.name, s.kind) for s in extract.symbols("routes.php", ROUTES_PHP, "php")}
    assert {("calculateQuote", "function"), ("QuoteService", "class"), ("quote", "method")} <= found


@pytest.mark.parametrize(
    ("file", "source", "lang", "text"),
    [
        ("charge.js", CHARGE_JS, "javascript", "Credit card info is invalid."),
        (
            "charge.js",
            CHARGE_JS,
            "javascript",
            "The credit card (ending ${lastFourDigits}) expired on ${month}/${year}.",
        ),
        ("index.js", INDEX_JS, "javascript", "Charge declined."),
        ("main.go", CHECKOUT_GO, "go", "failed to charge card: %+v"),
        ("main.go", CHECKOUT_GO, "go", "Failed to prepare OpAMP identity: %v"),
        ("main.go", CHECKOUT_GO, "go", "cart failure: %+v"),
        ("main.go", CHECKOUT_GO, "go", "environment variable not set"),
        ("CartService.cs", CART_CS, "csharp", "Can't access cart storage. {ex}"),
        ("CartService.cs", CART_CS, "csharp", "Wasn't able to connect to redis"),
        ("CartService.cs", CART_CS, "csharp", "Redis connection failed for {userId}"),
        ("routes.php", ROUTES_PHP, "php", "numberOfItems not provided"),
    ],
    ids=lambda v: v if isinstance(v, str) and len(v) < 40 and "\n" not in v else None,
)
def test_error_messages_are_found_with_their_line(file, source, lang, text):
    found = {(e.text, e.line) for e in extract.error_strings(file, source, lang)}
    assert (text, line_of(source, text.split("$")[0].split("%")[0])) in found


def test_only_literal_messages_are_kept():
    source = "function f() { throw new Error(message); throw err; }"
    assert extract.error_strings("x.js", source, "javascript") == []


