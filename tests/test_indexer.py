from app.indexer import build, card, export  # noqa: E402

FILES = {
    "src/payment/charge.js": CHARGE_JS,
    "src/payment/index.js": INDEX_JS,
    "src/payment/charge.test.js": "throw new Error('only in a test')",
    "src/payment/package.json": "{}",
}


def payment_index() -> build.CodeIndex:
    return build.build_index("payment", "f" * 40, FILES, PROTO)


def test_an_index_holds_one_service_at_one_commit():
    index = payment_index()
    assert index.service == "payment" and index.git_sha == "f" * 40
    assert {s.file for s in index.symbols} == {"src/payment/charge.js", "src/payment/index.js"}
    assert "only in a test" not in {e.text for e in index.errors}
    assert [(r.method, r.file) for r in index.rpcs] == [
        ("PaymentService/Charge", "src/payment/index.js")
    ]
    assert [f.flag for f in index.flags] == ["paymentFailure"]
    assert set(index.files) == {"src/payment/charge.js", "src/payment/index.js"}


def test_go_flag_keys_come_from_the_generated_file():
    files = {"src/checkout/main.go": CHECKOUT_GO, "src/checkout/flags/flags_gen.go": FLAGS_GEN_GO}
    index = build.build_index("checkout", "e" * 40, files, PROTO)
    assert [f.flag for f in index.flags] == ["paymentUnreachable"]
    assert "src/checkout/flags/flags_gen.go" not in {s.file for s in index.symbols}


def test_the_export_is_what_the_helper_commands_read(tmp_path):
    export.write(tmp_path, [payment_index()], {"payment": "# payment\nCharges cards."})
    symbols = [line.split("\t") for line in (tmp_path / "symbols.tsv").read_text().splitlines()]
    assert ["src/payment/index.js", "3", "payment", "function", "chargeServiceHandler"] == (
        next(s for s in symbols if s[4] == "chargeServiceHandler")[:5]
    )
    errors = [line.split("\t") for line in (tmp_path / "errors.tsv").read_text().splitlines()]
    expired = next(e for e in errors if "expired on" in e[3])
    assert expired[:3] == [
        "src/payment/charge.js",
        str(line_of(CHARGE_JS, "expired on")),
        "payment",
    ]
    assert re.search(expired[4], "The credit card (ending 4242) expired on 9/2026.")
    assert (
        (tmp_path / "rpc.tsv")
        .read_text()
        .startswith("PaymentService/Charge\tsrc/payment/index.js\t")
    )
    assert "paymentFailure\tsrc/payment/charge.js\t" in (tmp_path / "flags.tsv").read_text()
    assert (tmp_path / "cards" / "payment.md").read_text().startswith("# payment")


def test_the_export_keeps_one_record_per_line(tmp_path):
    index = payment_index()
    index.errors.append(extract.ErrorString("src/payment/x.js", 1, "two\tcolumns\nand lines"))
    export.write(tmp_path, [index], {})
    lines = (tmp_path / "errors.tsv").read_text().splitlines()
    assert all(len(line.split("\t")) == 5 for line in lines)


def test_the_export_is_readable_by_the_codebox_user():
    """The codebox runs as its own user, and mkdtemp makes a directory only its owner can read."""
    out = Path(tempfile.mkdtemp())
    try:
        export.write(out, [payment_index()], {"payment": "# payment"})
        for path in [out, *out.rglob("*")]:
            other = path.stat().st_mode & 0o007
            assert other == (0o005 if path.is_dir() else 0o004), path
    finally:
        shutil.rmtree(out)


async def test_a_service_card_is_written_from_the_code(monkeypatch):
    seen = {}

    async def fake_run(prompt: str) -> card.ServiceCard:
        seen["prompt"] = prompt
        return card.ServiceCard(
            purpose="Charges cards.",
            entry_points=["PaymentService/Charge: src/payment/index.js:3"],
            business_rules=["Only Visa and Mastercard are accepted."],
            dependencies=["flagd"],
            error_messages=[
                card.ErrorMeaning(message="Credit card info is invalid.", meaning="Bad number."),
                card.ErrorMeaning(message="Made up by the model.", meaning="?"),
            ],
        )

    monkeypatch.setattr(card, "_run", fake_run)
    text = await card.write_card(payment_index(), "Validates and charges cards.")
    assert "src/payment/charge.js" in seen["prompt"]
    assert f"{line_of(CHARGE_JS, 'expired on')}: " in seen["prompt"]  # the code has line numbers
    assert "PaymentService/Charge -> src/payment/index.js" in seen["prompt"]
    assert text.startswith("# payment at ffffffff")
    assert "Only Visa and Mastercard are accepted." in text
    assert "Credit card info is invalid." in text
    assert "Made up by the model." not in text  # only messages the code really has
