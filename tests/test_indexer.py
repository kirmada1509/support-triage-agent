def test_go_clients_are_not_handlers():
    """checkout calls the email service through its own sendOrderConfirmation(ctx, *pb...);
    a Go server's handler has the proto's exact, exported name."""
    client = (
        "package main\n"
        "func (cs *checkout) sendOrderConfirmation(ctx context.Context,\n"
        "\treq *pb.SendOrderConfirmationRequest) error {\n"
        "\treturn nil\n}\n"
    )
    proto = "service EmailService {\n  rpc SendOrderConfirmation(Req) returns (Empty) {}\n}\n"
    assert (
        extract.rpc_handlers({"src/checkout/main.go": client}, extract.proto_methods(proto)) == []
    )


